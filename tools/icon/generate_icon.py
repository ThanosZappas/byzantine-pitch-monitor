#!/usr/bin/env python3
"""Generates the launcher icon: a Byzantine wheel (the Wheel of Koukouzelis, the circular
diagram of the eight modes) in gold on cinnabar red.

Writes the adaptive-icon vector drawables into app/src/main/res and an SVG preview next to
this script. Run from the repository root:  python3 tools/icon/generate_icon.py
"""
import math
import os

GOLD = "#D9AE4E"
GOLD_LIGHT = "#F2D27A"
RED = "#7A1C14"
RED_DARK = "#4E100B"
C = 54.0  # centre of the 108x108 adaptive icon canvas (safe zone radius ~33)
SCALE = 0.86  # shrink the artwork a little so the outer ring breathes inside round masks


def circle(r, cx=C, cy=C):
    return f"M{cx - r:.2f},{cy:.2f} a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0 a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0 Z"


def polar(r, deg):
    a = math.radians(deg - 90)
    return C + r * math.cos(a), C + r * math.sin(a)


def build():
    """Returns a list of (kind, path, attrs) shapes. kind: 'stroke' or 'fill'."""
    shapes = []
    # Rings of the wheel.
    shapes.append(("stroke", circle(30.0), dict(color=GOLD, width=3.2)))
    shapes.append(("stroke", circle(21.5), dict(color=GOLD, width=2.0)))
    shapes.append(("stroke", circle(11.0), dict(color=GOLD, width=2.0)))
    # Four spokes dividing the wheel into the four quadrants (authentic + plagal pairs).
    spokes = ""
    for deg in (0, 90, 180, 270):
        x1, y1 = polar(11.0, deg)
        x2, y2 = polar(30.0, deg)
        spokes += f"M{x1:.2f},{y1:.2f} L{x2:.2f},{y2:.2f} "
    shapes.append(("stroke", spokes.strip(), dict(color=GOLD, width=2.4)))
    # Eight modes: small medallions on the outer band, two per quadrant.
    for k in range(8):
        x, y = polar(25.75, 22.5 + 45 * k)
        shapes.append(("fill", circle(2.7, x, y), dict(color=GOLD_LIGHT)))
    # Four inner points for the four authentic modes.
    for k in range(4):
        x, y = polar(16.25, 45 + 90 * k)
        shapes.append(("fill", circle(1.7, x, y), dict(color=GOLD)))
    # Hub with a small Greek cross.
    shapes.append(("fill", circle(6.0), dict(color=GOLD)))
    cross = (f"M{C - 0.9:.2f},{C - 4.0:.2f} h1.8 v3.1 h3.1 v1.8 h-3.1 v3.1 h-1.8 v-3.1 h-3.1 v-1.8 h3.1 Z")
    shapes.append(("fill", cross, dict(color=RED)))
    return shapes


def vector_xml(shapes, mono=False):
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tools/icon/generate_icon.py. Do not edit by hand. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp" android:height="108dp"',
        '    android:viewportWidth="108" android:viewportHeight="108">',
        f'    <group android:pivotX="{C}" android:pivotY="{C}" android:scaleX="{SCALE}" android:scaleY="{SCALE}">',
    ]
    for kind, d, a in shapes:
        color = "#FFFFFFFF" if mono else a["color"]
        if mono and a.get("color") == RED:
            continue  # the cross is a cut-out; skip in the single-colour layer
        if kind == "stroke":
            out.append(
                f'    <path android:pathData="{d}" android:strokeColor="{color}" '
                f'android:strokeWidth="{a["width"]}" android:strokeLineCap="round" android:fillColor="#00000000"/>'
            )
        else:
            out.append(f'    <path android:pathData="{d}" android:fillColor="{color}"/>')
    out.append("    </group>")
    out.append("</vector>")
    return "\n".join(out) + "\n"


def background_xml():
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icon/generate_icon.py. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="54" android:centerY="48"
                android:gradientRadius="76" android:startColor="{RED}" android:endColor="{RED_DARK}"/>
        </aapt:attr>
    </path>
    <path android:pathData="{circle(36.5)}" android:strokeColor="#33D9AE4E" android:strokeWidth="1" android:fillColor="#00000000"/>
</vector>
"""


def svg(shapes):
    parts = [
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="432" height="432">',
        '<defs><radialGradient id="bg" cx="50%" cy="44%" r="70%">'
        f'<stop offset="0" stop-color="{RED}"/><stop offset="1" stop-color="{RED_DARK}"/></radialGradient>'
        '<clipPath id="mask"><circle cx="54" cy="54" r="54"/></clipPath></defs>',
        '<g clip-path="url(#mask)"><rect width="108" height="108" fill="url(#bg)"/>',
        f'<path d="{circle(36.5)}" stroke="#D9AE4E" stroke-opacity="0.2" stroke-width="1" fill="none"/>',
        f'<g transform="translate({C} {C}) scale({SCALE}) translate({-C} {-C})">',
    ]
    for kind, d, a in shapes:
        if kind == "stroke":
            parts.append(f'<path d="{d}" stroke="{a["color"]}" stroke-width="{a["width"]}" stroke-linecap="round" fill="none"/>')
        else:
            parts.append(f'<path d="{d}" fill="{a["color"]}"/>')
    parts.append("</g></g></svg>")
    return "\n".join(parts)


def main():
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    res = os.path.join(root, "app", "src", "main", "res")
    shapes = build()
    files = {
        os.path.join(res, "drawable", "ic_launcher_foreground.xml"): vector_xml(shapes),
        os.path.join(res, "drawable", "ic_launcher_monochrome.xml"): vector_xml(shapes, mono=True),
        os.path.join(res, "drawable", "ic_launcher_background.xml"): background_xml(),
        os.path.join(os.path.dirname(os.path.abspath(__file__)), "icon-preview.svg"): svg(shapes),
    }
    for path, text in files.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote", os.path.relpath(path, root))


if __name__ == "__main__":
    main()
